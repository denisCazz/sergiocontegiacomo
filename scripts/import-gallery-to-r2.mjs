/**
 * Import local src/assets/gallery files into R2 + gallery_images.
 *
 * Usage:
 *   node --env-file=.env scripts/import-gallery-to-r2.mjs
 */

import { readdir, readFile } from 'node:fs/promises';
import { extname, join } from 'node:path';
import { PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import postgres from 'postgres';

const DATABASE_URL = process.env.DATABASE_URL;
const R2_ACCOUNT_ID = process.env.R2_ACCOUNT_ID;
const R2_ACCESS_KEY_ID = process.env.R2_ACCESS_KEY_ID;
const R2_SECRET_ACCESS_KEY = process.env.R2_SECRET_ACCESS_KEY;
const R2_BUCKET_NAME = process.env.R2_BUCKET_NAME || 'sergio-media';
const R2_PUBLIC_URL = (process.env.R2_PUBLIC_URL || '').replace(/\/$/, '');
const GALLERY_DIR = join(process.cwd(), 'src/assets/gallery');
const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif', '.svg']);

function altFromFilename(name) {
  const base = name.replace(/\.[^.]+$/, '');
  const cleaned = base.replace(/[_-]+/g, ' ').replace(/\s+/g, ' ').trim();
  if (!cleaned) return 'Immagine gallery';
  return cleaned.charAt(0).toUpperCase() + cleaned.slice(1);
}

function contentType(filename) {
  const lower = filename.toLowerCase();
  if (lower.endsWith('.png')) return 'image/png';
  if (lower.endsWith('.jpg') || lower.endsWith('.jpeg')) return 'image/jpeg';
  if (lower.endsWith('.webp')) return 'image/webp';
  if (lower.endsWith('.gif')) return 'image/gif';
  if (lower.endsWith('.avif')) return 'image/avif';
  if (lower.endsWith('.svg')) return 'image/svg+xml';
  return 'application/octet-stream';
}

if (!DATABASE_URL) {
  console.error('DATABASE_URL missing');
  process.exit(1);
}
if (!R2_ACCOUNT_ID || !R2_ACCESS_KEY_ID || !R2_SECRET_ACCESS_KEY) {
  console.error('R2 credentials missing');
  process.exit(1);
}

const sql = postgres(DATABASE_URL, { max: 5, connect_timeout: 20 });
const s3 = new S3Client({
  region: 'auto',
  endpoint: `https://${R2_ACCOUNT_ID}.r2.cloudflarestorage.com`,
  credentials: {
    accessKeyId: R2_ACCESS_KEY_ID,
    secretAccessKey: R2_SECRET_ACCESS_KEY,
  },
});

async function ensureTable() {
  await sql`
    CREATE TABLE IF NOT EXISTS public.gallery_images (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
      updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
      image_url TEXT NOT NULL,
      alt TEXT NOT NULL DEFAULT '',
      caption TEXT,
      display_order INTEGER NOT NULL DEFAULT 0,
      is_published BOOLEAN NOT NULL DEFAULT true,
      source_filename TEXT UNIQUE
    )
  `;
  await sql`
    CREATE INDEX IF NOT EXISTS gallery_images_public_idx
    ON public.gallery_images (is_published, display_order)
  `;
}

async function main() {
  await ensureTable();
  const files = (await readdir(GALLERY_DIR))
    .filter((name) => IMAGE_EXT.has(extname(name).toLowerCase()))
    .sort((a, b) => a.localeCompare(b, 'it'));

  console.log(`Found ${files.length} gallery files`);
  let imported = 0;
  let skipped = 0;

  for (const filename of files) {
    const existing = await sql`
      SELECT id FROM gallery_images WHERE source_filename = ${filename} LIMIT 1
    `;
    if (existing.length) {
      console.log(`skip ${filename}`);
      skipped += 1;
      continue;
    }

    const body = await readFile(join(GALLERY_DIR, filename));
    const sanitized = filename.toLowerCase().replace(/[^a-z0-9.-]/g, '_').replace(/_+/g, '_');
    const key = `images/${Date.now()}_${sanitized}`;
    await s3.send(
      new PutObjectCommand({
        Bucket: R2_BUCKET_NAME,
        Key: key,
        Body: body,
        ContentType: contentType(filename),
      })
    );

    const url = R2_PUBLIC_URL
      ? `${R2_PUBLIC_URL}/${key}`
      : `https://pub-${R2_ACCOUNT_ID}.r2.dev/${key}`;

    const nextOrderRows = await sql`
      SELECT COALESCE(MAX(display_order), 0) + 1 AS next FROM gallery_images
    `;
    const nextOrder = Number(nextOrderRows[0].next) || 1;

    await sql`
      INSERT INTO gallery_images (image_url, alt, caption, display_order, is_published, source_filename)
      VALUES (
        ${url},
        ${altFromFilename(filename)},
        ${null},
        ${nextOrder},
        ${true},
        ${filename}
      )
    `;
    console.log(`ok   ${filename} -> ${url}`);
    imported += 1;
  }

  console.log(`Done. imported=${imported} skipped=${skipped}`);
  await sql.end({ timeout: 5 });
}

main().catch(async (err) => {
  console.error(err);
  await sql.end({ timeout: 5 }).catch(() => {});
  process.exit(1);
});
